export function pickRandomUnique(pool, count) {
  const copy = [...pool];
  const result = [];
  for (let i = 0; i < count && copy.length > 0; i++) {
    const idx = Math.floor(Math.random() * copy.length);
    result.push(copy[idx]);
    copy.splice(idx, 1);
  }
  return result;
}

export function makeCard() {
  return {
    words: pickRandomUnique(WORD_POOL, 3),
    criteria: pickRandomUnique(CRITERIA_POOL, 1)[0],
  };
}
